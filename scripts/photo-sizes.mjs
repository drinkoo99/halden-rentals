// Regenerates src/data/photoSizes.ts: intrinsic width/height of every file in public/images.
// Run after adding or upscaling photos:  node scripts/photo-sizes.mjs
import { readdirSync, writeFileSync } from "node:fs";
import sharp from "sharp";

const dir = new URL("../public/images/", import.meta.url);
const rows = [];
for (const f of readdirSync(dir).sort()) {
  if (!/\.(jpe?g|png|webp|avif)$/i.test(f)) continue;
  const { width, height } = await sharp(new URL(f, dir).pathname.replace(/^\/([A-Za-z]:)/, "$1")).metadata();
  rows.push(`  "/images/${f}": [${width}, ${height}],`);
}
writeFileSync(
  new URL("../src/data/photoSizes.ts", import.meta.url),
  `// Generated by scripts/photo-sizes.mjs — intrinsic [width, height] of each photo in public/images.\nexport const photoSizes: Record<string, readonly [number, number]> = {\n${rows.join("\n")}\n};\n`,
);
console.log(rows.length, "photos");
